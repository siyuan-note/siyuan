import * as assert from "node:assert/strict";
import {join} from "node:path";
import test from "node:test";
import {compile} from "sass";
import {browserSources, canRunBrowser, runBrowserCase} from "./test/browser";

test("inline dates share a calendar, validate drafts, isolate keys and preserve values on destroy", {
    timeout: 45000, skip: !canRunBrowser,
}, async () => {
    const sources = browserSources(Object.fromEntries(["model", "yearInput", "field", "inline"].map(name => [name, join(__dirname, name + ".ts")])));
    const result = await runBrowserCase(async (source, css) => {
        const equal = (actual: unknown, expected: unknown, message: string) => {
            if (actual !== expected) { throw new Error(`${message}: ${actual} !== ${expected}`); }
        };
        const modules: Record<string, any> = {};
        for (const name of ["model", "yearInput", "field", "inline"]) {
            const exports = modules[name] = {};
            new Function("exports", "require", source[name])(exports, (path: string) => modules[path.split("/").at(-1)]);
        }
        const languages = {date: "Date", datePickerTime: "Time", month: "Month", year: "Year", previous: "Previous", next: "Next",
            calendarToday: "Today", clear: "Clear", invalid: "Invalid", startDate: "Start date", endDate: "End date"};
        const style = document.createElement("style");
        style.textContent = css + ".fn__none{display:none}body{margin:0}.b3-text-field{box-sizing:border-box;max-width:100%}";
        document.head.append(style);
        const owner = document.createElement("div");
        owner.innerHTML = '<input type="date" value="2026-02-10"><input type="date" value="2026-02-20"><input type="checkbox"><input type="checkbox"><div></div>';
        document.body.append(owner);
        const inputs = owner.querySelectorAll<HTMLInputElement>("input");
        const host = owner.querySelector("div");
        let changes = 0;
        let inputEvents = 0;
        let parentKeys = 0;
        owner.addEventListener("change", () => changes++);
        owner.addEventListener("input", () => inputEvents++);
        owner.addEventListener("keydown", () => parentKeys++);
        const handle = modules.inline.bindInlineDatePicker(host, [inputs[0], inputs[1]], {languages});
        equal(inputs[0].type, "text", "Text inputs cannot invoke mobile native date surfaces");
        equal(modules.inline.getInlineDateType(inputs[0]), "date", "Original date semantics remain available");
        equal(owner.querySelectorAll("input")[2], inputs[2], "Year controls do not displace business input indexes");
        equal(host.querySelectorAll(".date-picker__fields, .date-picker__shortcuts").length, 0, "No duplicate fields or business clear actions");
        equal(host.querySelectorAll("table").length, 0, "Mounting does not expand every calendar in a form");
        equal(changes, 0, "Mount never saves");
        inputs[1].focus();
        equal(host.querySelectorAll("table").length, 1, "Both endpoints share one calendar after focus");
        equal(handle.isActive(inputs[1]), true, "Endpoint follows focus");
        equal(host.querySelector('[role="status"]').textContent, "End date", "Calendar identifies its endpoint even when input loses focus");
        const day = () => host.querySelector<HTMLButtonElement>('button[data-date="2026-02-21"]');
        day().click();
        equal(inputs[1].value, "2026-02-21", "Calendar updates the active endpoint");
        equal(inputs[0].value, "2026-02-10", "Other endpoint is untouched");
        equal(changes, 1, "Selection dispatches one change");
        equal(inputEvents, 1, "Changed selection dispatches one input");
        day().click();
        equal(changes, 2, "Same-day explicit selection is an intentional commit");
        const toggle = host.querySelector<HTMLButtonElement>(".date-picker__month-toggle");
        toggle.click();
        const year = host.querySelector<HTMLInputElement>(".date-picker__month-editor input");
        year.value = "2027";
        year.dispatchEvent(new Event("input", {bubbles: true}));
        equal(changes, 2, "Year browsing never saves");
        year.dispatchEvent(new KeyboardEvent("keydown", {key: "Enter", bubbles: true, cancelable: true}));
        equal(parentKeys, 0, "Year Enter does not submit the host");
        toggle.click();
        year.dispatchEvent(new KeyboardEvent("keydown", {key: "Escape", bubbles: true, cancelable: true}));
        equal(parentKeys, 0, "First Escape closes only the month editor");
        toggle.dispatchEvent(new KeyboardEvent("keydown", {key: "Escape", bubbles: true}));
        equal(parentKeys, 1, "Outer Escape remains available");
        const tab = new KeyboardEvent("keydown", {key: "Tab", bubbles: true, cancelable: true});
        toggle.dispatchEvent(tab);
        equal(tab.defaultPrevented, false, "Tab retains native focus traversal");
        inputs[1].value = "2026-02-31";
        inputs[1].dispatchEvent(new Event("input", {bubbles: true}));
        equal(handle.validate(), false, "Impossible date draft blocks confirmation");
        equal(inputs[1].value, "2026-02-31", "Invalid text remains visible");
        equal(changes, 2, "Typing does not dispatch synthetic change");
        inputs[1].value = "2026-02-22";
        inputs[1].dispatchEvent(new Event("input", {bubbles: true}));
        inputs[1].dispatchEvent(new CompositionEvent("compositionstart", {bubbles: true}));
        equal(handle.validate(), false, "IME draft blocks confirmation");
        inputs[1].dispatchEvent(new CompositionEvent("compositionend", {bubbles: true}));
        equal(handle.validate(), true, "Completed valid text can submit");
        inputs[1].min = "2026-02-23";
        handle.update();
        equal(handle.validate(), false, "Dynamic minimum uses native validation");
        inputs[1].value = "2026-02-24";
        inputs[1].step = "2";
        handle.update();
        equal(handle.validate(), false, "Native step base uses the minimum");
        inputs[1].step = "any";
        handle.update();
        equal(handle.validate(), true, "Explicit update synchronizes constraints");
        equal(changes, 2, "Updates never save");
        const guardedDay = host.querySelector<HTMLButtonElement>("button[data-date]");
        const guardedValue = inputs[1].value;
        inputs[1].readOnly = true;
        guardedDay.click();
        equal(inputs[1].value, guardedValue, "Readonly endpoint rejects existing calendar events immediately");
        await new Promise(resolve => setTimeout(resolve, 0));
        equal(inputs[0].dataset.datePickerActive, "true", "Readonly endpoint moves the calendar to an available endpoint");
        inputs[1].readOnly = false;
        handle.update();
        handle.activate(inputs[1]);
        inputs[1].disabled = true;
        host.querySelector<HTMLButtonElement>("button[data-date]").click();
        equal(inputs[1].value, guardedValue, "Disabled endpoint rejects writes before observer delivery");
        inputs[1].disabled = false;
        handle.update();
        inputs[1].required = true;
        inputs[1].value = "";
        handle.update();
        equal(handle.validate(), false, "Required clear is invalid");
        inputs[1].classList.add("fn__none");
        handle.update();
        equal(handle.validate(), true, "Hidden endpoints do not block submission");
        equal(host.getBoundingClientRect().right <= innerWidth, true, "Calendar fits a narrow viewport");
        inputs[0].value = "2026-02-";
        inputs[0].dispatchEvent(new Event("input", {bubbles: true}));
        const staleDay = host.querySelector<HTMLButtonElement>("button[data-date]");
        handle.destroy();
        equal(inputs[0].value, "2026-02-", "Connected destroy preserves incomplete text");
        equal(inputs[0].validity.valid, false, "Destroyed invalid draft cannot masquerade as valid empty");
        staleDay.click();
        equal(changes, 2, "Stale buttons cannot save after destroy");
        equal(host.children.length, 0, "Destroy removes only owned content");
        inputs[0].value = "2026-02-10";
        const remounted = modules.inline.bindInlineDatePicker(host, inputs[0], {languages});
        equal(remounted.validate(), true, "Remount can recover a preserved text draft");
        owner.remove();
        await new Promise(resolve => setTimeout(resolve, 0));
        equal(host.children.length, 0, "Detached host cleans itself without saving");
        equal(changes, 2, "Detach never saves");
        const timeOwner = document.createElement("div");
        timeOwner.innerHTML = '<input type="datetime-local" step="any" value="2026-03-01T12:34:56.123"><div></div>';
        document.body.append(timeOwner);
        const time = timeOwner.querySelector("input");
        const timeHost = timeOwner.querySelector("div");
        const timeHandle = modules.inline.bindInlineDatePicker(timeHost, time, {languages});
        equal(timeHandle.validate(), true, "Allowed fractional seconds are valid");
        timeHandle.destroy();
        equal(time.value, "2026-03-01 12:34:56.123", "Destroy preserves visible seconds and milliseconds");
        time.type = "time";
        time.value = "12:34:56.123";
        const clock = modules.inline.bindInlineDatePicker(timeHost, time, {languages});
        equal(timeHost.querySelectorAll("table, .date-picker__fields, button").length, 0, "Time has no duplicate UI");
        equal(time.type, "text", "Time cannot invoke a native popup");
        clock.destroy();
        const initialText = document.createElement("input");
        initialText.type = "text";
        initialText.dataset.datePickerType = "date";
        initialText.value = "2026-01-";
        timeOwner.prepend(initialText);
        const mode = modules.inline.bindInlineDatePicker(timeHost, initialText, {languages});
        initialText.classList.add("fn__none");
        mode.update();
        equal(initialText.value, "2026-01-", "Current-time mode hiding preserves unfinished static draft");
        equal(mode.validate(), true, "Hidden static draft does not block current-time mode");
        initialText.classList.remove("fn__none");
        mode.update();
        equal(mode.validate(), false, "Returning to static mode restores the draft error");
        mode.destroy();
        equal(initialText.type, "text", "Initially text sources never become native on destroy");
        equal(initialText.value, "2026-01-", "Mode teardown preserves incomplete text");
        initialText.value = "2026-01-15";
        const moved = modules.inline.bindInlineDatePicker(timeHost, initialText, {languages});
        moved.activate(initialText);
        const staleMovedDay = timeHost.querySelector<HTMLButtonElement>("button[data-date]");
        const iframe = document.createElement("iframe");
        document.body.append(iframe);
        iframe.contentDocument.body.append(initialText);
        staleMovedDay.click();
        equal(initialText.value, "2026-01-15", "Adopted inputs reject old-document calendar writes");
        await new Promise(resolve => setTimeout(resolve, 0));
        equal(timeHost.children.length, 0, "Moving the input to another document disposes its calendar");
        moved.destroy();
        return "inline date cases passed";
    }, sources, compile("src/assets/scss/component/_date-picker.scss").css, {width: 320, height: 900});
    assert.match(result, /inline date cases passed/);
});
