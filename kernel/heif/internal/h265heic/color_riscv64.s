	PIXEL(V9)
	PIXEL(V10)

	VSETVLI  X5, E8, MF4, TA, MA, X6
	VLE8V    (X16), V11
	VSETVLI  X5, E32, M1, TA, MA, X6
	VZEXTVF4 V11, V12

	NARROW(V8, V16)
	NARROW(V9, V17)
	NARROW(V10, V18)
	NARROW(V12, V19)

	VSETVLI   X5, E8, MF4, TA, MA, X6
	VSSEG4E8V V16, (X10)
	VSETVLI   X5, E32, M1, TA, MA, X6

	SLLI $2, X5, X6
	ADD  X6, X11
	ADD  X6, X10
	ADD  X6, X10
	ADD  X6, X10
	ADD  X6, X10
	SUB  X6, X10
	SUB  X6, X10
	SUB  X6, X10
	SRLI $1, X6, X20
	ADD  X20, X12
	ADD  X20, X13
	ADD  X20, X14
	ADD  X20, X15
	ADD  X5, X16
	SUB  X5, X17
	BNEZ X17, loop

	RET

