#define CHROMA(P0, P1, OUT)      \
	VLE32V     (P0), V3;     \
	VRGATHERVV V6, V3, V4;   \
	VRGATHERVV V7, V3, V5;   \
	VFMULVF    F0, V4, OUT;  \
	VFMULVF    F1, V5, V5;   \
	VFADDVV    V5, OUT, OUT; \
	VLE32V     (P1), V3;     \
	VRGATHERVV V6, V3, V4;   \
	VRGATHERVV V7, V3, V5;   \
	VFMULVF    F1, V4, V4;   \
	VFADDVV    V4, OUT, OUT; \
	VFMULVF    F2, V5, V5;   \
	VFADDVV    V5, OUT, OUT

#define PIXEL(V)             \
	VFMAXVF     F11, V, V; \
	VFMINVF     F9, V, V;  \
	VFMULVF     F8, V, V;  \
	VFADDVF     F10, V, V; \
	VFCVTRTZXFV V, V

#define NARROW(SRC, DST)                   \
	VSETVLI X5, E16, MF2, TA, MA, X6;  \
	VNSRLWI $0, SRC, V20;              \
	VSETVLI X5, E8, MF4, TA, MA, X6;   \
	VNSRLWI $0, V20, DST;              \
	VSETVLI X5, E32, M1, TA, MA, X6

// func convertRowRVV(dst *uint8, yf, u0, u1, v0, v1 *float32, a *uint8, n int, c *rowConsts)
TEXT ·convertRowRVV(SB), NOSPLIT, $0-72
	MOV dst+0(FP), X10
