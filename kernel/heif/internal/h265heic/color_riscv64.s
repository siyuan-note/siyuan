	VFMULVF F4, V1, V10
	VFADDVV V0, V10, V10

	VFMULVF F5, V2, V9
	VFMULVF F6, V1, V4
	VFADDVV V4, V9, V9
	VFADDVV V9, V9, V9
	VFDIVVF F7, V9, V9
	VFSUBVV V9, V0, V9

