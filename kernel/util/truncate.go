package util

import "unicode/utf8"

// TruncateRunes 按 Unicode 码点截断文本，不附加省略标记。
func TruncateRunes(text string, maxRunes int) string {
	if maxRunes <= 0 {
		return ""
	}
	runes := []rune(text)
	if len(runes) <= maxRunes {
		return text
	}
	return string(runes[:maxRunes])
}

// TruncateUTF8Bytes 在字节上限内截断有效 UTF-8 文本，保留完整码点，不附加省略标记。
func TruncateUTF8Bytes(text string, maxBytes int) string {
	if maxBytes <= 0 {
		return ""
	}
	if len(text) <= maxBytes {
		return text
	}
	end := maxBytes
	for end > 0 && !utf8.ValidString(text[:end]) {
		end--
	}
	return text[:end]
}
